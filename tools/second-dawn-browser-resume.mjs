import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const directory='coding_agents/second_dawn_live';
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:5175/');
await page.getByRole('button',{name:'New game',exact:true}).click();
await page.getByRole('button',{name:'Start game',exact:true}).click();
await page.getByRole('button',{name:'Game menu',exact:true}).waitFor();
const before=await page.locator('.sd-turn').innerText();
const saved=await page.evaluate(()=>localStorage.getItem('eclipse.second-dawn.match.v1'));
await page.reload();
await page.getByRole('button',{name:/Continue · round/}).first().click();
await page.getByRole('button',{name:'Game menu',exact:true}).waitFor();
const after=await page.locator('.sd-turn').innerText();
if(before!==after||saved!==await page.evaluate(()=>localStorage.getItem('eclipse.second-dawn.match.v1')))throw Error('Resume changed the saved match.');
await page.locator('.sd-frontier').first().click();
await page.context().setOffline(true);
await page.getByText('Disconnected · waiting to reconnect',{exact:true}).waitFor();
const disabled=await page.getByRole('button',{name:'Confirm action',exact:true}).isDisabled();
if(!disabled)throw Error('Offline submission was enabled.');
await page.screenshot({path:`directory/offline.png`.replace('directory',directory)});
await page.context().setOffline(false);
await page.waitForFunction(()=>!document.querySelector('.dg-action-panel .sd-primary')?.disabled);
await page.getByRole('button',{name:'Confirm action',exact:true}).click();
await page.locator('.dg-exploration-decision').getByRole('heading',{name:/^exploration$/i}).waitFor();
await page.reload();
await page.getByRole('button',{name:/Continue · round/}).first().click();
await page.locator('.dg-exploration-decision').getByRole('heading',{name:/^exploration$/i}).waitFor();
await page.screenshot({path:`${directory}/resumed-exploration.png`});
await writeFile(`${directory}/browser-resume.json`,JSON.stringify({review:'Agent browser automation, not a human playtest',backend:'http://127.0.0.1:3210',savedMatchId:saved,sameRoundAfterReload:before===after,offlineSubmissionDisabled:disabled,reconnectedCommandAccepted:true,explorationDecisionSurvivedReload:true,pageErrors:errors},null,2));
await browser.close();
console.log('Browser guest creation, reload resume, offline submission guard, reconnect, and interrupted exploration resume passed.');
